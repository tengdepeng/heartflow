/** 内置汉字库 */
export const HANZI_DATA: HanziEntry[] = RAW.map((r) => {
  const [char, pinyin, noTone, initial, radical, radicalStrokes, strokes, structure, meaning, ...words] = r
  BUILTIN_SET.add(char)
  return { char, pinyin, noTone, initial, radical, radicalStrokes, strokes, structure, meaning, words }
})

const CUSTOM_KEY = 'hf:hanzi_custom'

function loadCustom(): HanziEntry[] {
  try { return storage.getKV<HanziEntry[]>(CUSTOM_KEY, []) } catch { return [] }
}

function saveCustom(list: HanziEntry[]): void {
  try { storage.setKV(CUSTOM_KEY, list) } catch { /* 静默 */ }
}

/** 读取全部汉字（内置 + 用户扩展），用户扩展在前排 */
export function loadHanziAll(): HanziEntry[] {
  return [...loadCustom(), ...HANZI_DATA]
}

/** 追加一个自定义汉字（内置字忽略）；返回是否成功新增 */
export function addHanzi(entry: Omit<HanziEntry, 'char'> & { char: string }): boolean {
  if (BUILTIN_SET.has(entry.char)) return false
  const custom = loadCustom()
  if (custom.some((c) => c.char === entry.char)) return false
  custom.push({ ...entry, words: entry.words ?? [] })
  saveCustom(custom)
  return true
}

/** 删除一个自定义汉字（内置字无法删除）；返回是否删除成功 */
export function removeHanzi(char: string): boolean {
  if (BUILTIN_SET.has(char)) return false
  const before = loadCustom()
  const after = before.filter((c) => c.char !== char)
  if (after.length === before.length) return false
  saveCustom(after)
  return true
}