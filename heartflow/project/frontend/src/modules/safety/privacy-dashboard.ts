  /** 撤销权限 */
  function revokePermission(permissionId: string): boolean {
    const perm = permissions.value.find(p => p.id === permissionId)
    if (!perm || !perm.revocable) return false

    perm.granted = false
    perm.grantedAt = null
    persistPermissions()
    return true
  }

