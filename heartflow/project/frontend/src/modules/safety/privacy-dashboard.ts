/** 估算数据量 */
function estimateDataCount(category: DataCategory): number {
  const storageKeys: Partial<Record<DataCategory, string>> = {
    emotion: 'hf:emotion_records',
    diary: 'hf:diary_entries',
    personal: 'hf:user_profile',
    health: 'hf:health_data',
    system: 'hf:safety_config',
  }

  const key = storageKeys[category]
  if (!key) return 0

  try {
    const data = localStorage.getItem(key)
    if (!data) return 0
    const parsed = JSON.parse(data)
    if (Array.isArray(parsed)) return parsed.length
    return 1
  } catch {
    return 0
  }
}

/** 估算数据大小 */
function estimateDataSize(category: DataCategory): number {
  const storageKeys: Partial<Record<DataCategory, string>> = {
    emotion: 'hf:emotion_records',
    diary: 'hf:diary_entries',
    personal: 'hf:user_profile',
    health: 'hf:health_data',
    system: 'hf:safety_config',
  }

  const key = storageKeys[category]
  if (!key) return 0

  try {
    const data = localStorage.getItem(key)
    if (!data) return 0
    return new Blob([data]).size
  } catch {
    return 0
  }
}

/** 判断存储位置 */
function determineStorageLocation(category: DataCategory): StorageLocation {
  // 敏感数据默认加密本地存储
  const sensitiveCategories: DataCategory[] = ['emotion', 'diary', 'personal', 'health', 'financial']
  if (sensitiveCategories.includes(category)) return 'encrypted_local'
  return 'local'
}

/** 判断数据是否加密 */
function isDataEncrypted(category: DataCategory): boolean {
  const encryptedCategories: DataCategory[] = ['emotion', 'diary', 'personal', 'health', 'financial']
  return encryptedCategories.includes(category)
}

/** 判断暴露面状态 */
function determineExposureStatus(
  category: DataCategory,
  count: number,
  _size: number,
): ExposureStatus {
  // 无数据
  if (count === 0) return 'safe'

  // 健康的敏感数据需要加密
  if (['emotion', 'diary', 'personal', 'health'].includes(category)) {
    return isDataEncrypted(category) ? 'monitored' : 'exposed'
  }

  // 大容量数据需要监控
  if (count > 500) return 'monitored'

  return 'safe'
}

/** 计算暴露面风险评分 */
function calculateExposureRisk(
  sensitivity: SensitivityLevel,
  status: ExposureStatus,
  _count: number,
): number {
  const sensitivityScore = SENSITIVITY_META[sensitivity].score
  const statusMultiplier = status === 'safe' ? 0.5
    : status === 'monitored' ? 0.7
    : status === 'exposed' ? 1.0
    : status === 'at_risk' ? 1.3
    : 1.5

  return Math.min(100, Math.round(sensitivityScore * statusMultiplier))
}

